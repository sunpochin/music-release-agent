/**
 * =====================================================================
 * 📝 Lyrics Prompt — 歌詞翻譯提示詞的單一事實來源
 * =====================================================================
 * [技術] Gemini 與 Ollama 兩個 provider 共用同一份 prompt，
 *        避免兩邊各寫一份悄悄漂移（與 handoff 契約同一哲學）。
 *        PROMPT_VERSION 是快取失效的核心機制：
 *        歌詞翻譯是「不可變內容」（歌詞不會變），所以不用 TTL；
 *        唯一合理的失效時機是 prompt 或模型改版 —
 *        改這份檔案時把版本 +1，所有舊快取自然 miss、重新生成。
 * [童趣] 這是廚房的「總食譜」：兩位廚師（Gemini / Ollama）都照
 *        同一本食譜做菜。食譜改版號碼 +1，以前做好的冷凍菜
 *        就自動視為過期，客人會吃到新食譜的菜。
 * =====================================================================
 */

/** 改 prompt 或換模型時 +1（快取失效的唯一開關）
 *  v2：接上 LRCLIB 真實歌詞來源 — 有原文時 LLM 只翻譯、不再「憑記憶找詞」 */
export const PROMPT_VERSION = 8;

export const SYSTEM_INSTRUCTION =
  '你是一位精通多國語言且極具文學素養的資深樂評人，擅長將外文歌詞翻譯為優美、感性且富含意境的繁體中文。';

const OUTPUT_FORMAT = `
請提供完整原文歌詞與「繁體中文」翻譯對照。
特別注意：
1. 如果判斷原文歌詞是「日文羅馬拼音 (Romaji)」，請務必在中文翻譯的上方，額外提供一行「日文原文 (漢字/假名)」。
2. 如果判斷原文歌詞是「日文 (包含漢字/假名)」，請務必在中文翻譯的上方，額外提供一行「羅馬拼音 (Romaji)」。
請直接輸出歌詞內容，不要在原文或翻譯前後加上中括號 [ ]，且不需要加上「中文翻譯：」或「日文原文：」之類的前綴。

排版請使用 Markdown 格式，請依照此結構：

### 歌詞對照
(填入原文第一行)
(若是日文歌曲，在此行填入對應的日文原文或羅馬拼音；若非日文則直接省略此行)
(填入繁體中文翻譯)

(填入原文第二行)
(若是日文歌曲，在此行填入對應的日文原文或羅馬拼音；若非日文則直接省略此行)
(填入繁體中文翻譯)

請確保翻譯感性且通順，符合音樂的意境。
`;

/**
 * @param {string} artistName
 * @param {string} trackName
 * @param {string} [sourceLyrics] 來自歌詞庫的真實原文。提供時 LLM 只翻譯，
 *                                嚴禁更改或補寫原文（消滅幻覺）；未提供時
 *                                退回記憶模式（來源故障的降級路徑）。
 */
export function buildLyricsPrompt(artistName, trackName, sourceLyrics) {
  if (sourceLyrics) {
    return `
以下是歌曲的「真實原文歌詞」（來自歌詞資料庫，請以此為唯一依據）：
- 歌手：${artistName}
- 歌名：${trackName}

<original_lyrics>
${sourceLyrics}
</original_lyrics>

請「只」針對上面提供的原文進行翻譯 — 嚴禁更改、增補或省略任何一句原文歌詞。請注意：結尾請不要加上任何樂評或賞析，只要純歌詞對照即可。
${OUTPUT_FORMAT}`;
  }

  return `
我們目前在資料庫中找不到以下歌曲的歌詞：
- 歌手：${artistName}
- 歌名：${trackName}

請不要自行生成或幻想任何歌詞原文與翻譯。請提供：
1. 在輸出內容的開頭，必須包含以下區塊：
### 歌詞說明
⚠️ 找不到本首歌曲的可驗證歌詞來源。

2. 接著可以提供一段針對該歌曲的短評賞析（以繁體中文撰寫，約 100-150 字）。

排版請使用 Markdown 格式，例如：

### 歌詞說明
⚠️ 找不到本首歌曲的可驗證歌詞來源。

### 歌曲短評
[短評內容]
`;
}

